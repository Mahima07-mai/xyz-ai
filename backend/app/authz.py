# ============================================================================
# Constants
# ============================================================================

ALLOWED_ROLES = frozenset(
    {
        "teacher",
        "student",
        "parent",
        "principal",
    }
)

ALLOWED_SUBJECTS = frozenset(
    {
        "Maths",
        "Science",
        "Language",
        "Social",
        "Technology",
    }
)


# ============================================================================
# Exceptions
# ============================================================================

class AuthorizationError(Exception):
    """
    Raised whenever an authenticated caller is not authorized to access
    a requested resource.

    Authorization failures intentionally use a single exception hierarchy
    so callers cannot accidentally continue execution after a failed check.
    """

    def __init__(self, message: str):
        self.message = message
        super().__init__(message)


class ClarificationNeeded(AuthorizationError):
    """
    Indicates that authorization succeeded up to the point where the
    requested resource is ambiguous.

    Example:
        A parent has two children and says "show my child's marks".

    This is not an authorization bypass.  No protected data is returned
    until the caller identifies one of their already-authorized children.
    """

    def __init__(self, message: str, options: list[str]):
        self.options = options
        super().__init__(message)


# ============================================================================
# Caller validation
# ============================================================================

def _caller_role(caller: dict[str, Any]) -> str:
    """
    Extract and validate the role from the verified auth.py caller context.

    Never accepts role aliases or role claims supplied separately by a
    caller/tool.
    """
    if not isinstance(caller, dict):
        raise AuthorizationError("Invalid authenticated user context.")

    role = caller.get("role")

    if not isinstance(role, str):
        raise AuthorizationError("Authenticated user role is missing.")

    role = role.strip().lower()

    if role not in ALLOWED_ROLES:
        raise AuthorizationError("Authenticated user has an invalid role.")

    return role


def _caller_id(caller: dict[str, Any]) -> str:
    """
    Extract the authenticated subject ID generated by auth.py.

    auth.py places the JWT `sub` claim into `caller["id"]`.
    """
    if not isinstance(caller, dict):
        raise AuthorizationError("Invalid authenticated user context.")

    subject_id = caller.get("id")

    if subject_id is None:
        raise AuthorizationError("Authenticated user identity is missing.")

    subject_id = str(subject_id).strip()

    if not subject_id:
        raise AuthorizationError("Authenticated user identity is empty.")

    return subject_id


def _caller_name(caller: dict[str, Any]) -> str:
    """Return the verified display name, or an empty string."""
    name = caller.get("name", "")

    if name is None:
        return ""

    return str(name).strip()


def _normalize(value: Any) -> str:
    """Normalize user-supplied lookup values for safe comparison."""
    if value is None:
        return ""

    return str(value).strip().casefold()


def _normalize_list(value: Any) -> list[str]:
    """
    Normalize JSON/ARRAY values stored in AuthTeacher.

    The current model uses JSONB for classes, sections and subjects.
    This helper also tolerates a legacy scalar value without granting
    broader access.
    """
    if value is None:
        return []

    if isinstance(value, (list, tuple, set)):
        values = value
    else:
        values = [value]

    return [
        str(item).strip()
        for item in values
        if item is not None and str(item).strip()
    ]


