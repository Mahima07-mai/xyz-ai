def authorization_context(
    db: Session,
    caller: dict[str, Any],
) -> dict[str, Any]:
    """
    Return a non-sensitive authorization snapshot useful for logging.

    No password/hash/token material is returned.

    This function is deliberately informational; callers must still execute
    the appropriate verify_* guard before accessing a protected resource.
    """
    role = _caller_role(caller)
    subject_id = _caller_id(caller)

    context: dict[str, Any] = {
        "id": subject_id,
        "role": role,
        "name": _caller_name(caller),
    }

    if role == "teacher":
        teacher = get_authenticated_teacher(db, caller)

        context.update(
            {
                "classes": _normalize_list(teacher.classes),
                "sections": _normalize_list(teacher.sections),
                "subjects": _normalize_list(teacher.subject_handled),
            }
        )

    elif role == "student":
        student = get_authenticated_student(db, caller)

        context.update(
            {
                "class_name": student.class_name,
                "section": student.section,
            }
        )

    elif role == "parent":
        parent = get_authenticated_parent(db, caller)

        context.update(
            {
                "child_student_id": parent.child_student_id,
            }
        )

    return context