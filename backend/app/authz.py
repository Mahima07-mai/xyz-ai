# Query scoping helpers
# ============================================================================

def authorized_student_ids(
    db: Session,
    caller: dict[str, Any],
    *,
    class_name: str | None = None,
    section: str | None = None,
) -> list[str]:
    """
    Return the exact student IDs visible to the authenticated caller.

    This helper is useful for analytics/reporting queries because the caller
    should first obtain an authorization scope and only then query marks,
    attendance, etc.

    Scope:
        principal -> all students, optionally filtered by class/section
        student   -> own student
        parent    -> linked child
        teacher   -> assigned class/section, optionally narrowed by the
                     explicitly requested class/section
    """
    role = _caller_role(caller)

    query = db.query(AuthStudent)

    if role == "principal":
        if class_name is not None:
            query = query.filter(AuthStudent.class_name == class_name)

        if section is not None:
            query = query.filter(AuthStudent.section == section)

        return [
            student.student_id
            for student in query.all()
        ]

    if role == "student":
        student = get_authenticated_student(db, caller)

        if class_name is not None and _normalize(student.class_name) != _normalize(class_name):
            raise AuthorizationError(
                "Students cannot query another class."
            )

        if section is not None and _normalize(student.section) != _normalize(section):
            raise AuthorizationError(
                "Students cannot query another section."
            )

        return [student.student_id]

    if role == "parent":
        child = verify_parent_access(db, caller)

        if class_name is not None and _normalize(child.class_name) != _normalize(class_name):
            raise AuthorizationError(
                "The requested class is outside your child's scope."
            )

        if section is not None and _normalize(child.section) != _normalize(section):
            raise AuthorizationError(
                "The requested section is outside your child's scope."
            )

        return [child.student_id]

    if role == "teacher":
        teacher = get_authenticated_teacher(db, caller)

        if class_name is not None or section is not None:
            if class_name is None or section is None:
                raise AuthorizationError(
                    "Both class and section must be supplied together."
                )

            if not teacher_handles_class_section(
                teacher,
                class_name,
                section,
            ):
                raise AuthorizationError(
                    "You are not authorized to access that class and section."
                )

            query = query.filter(
                AuthStudent.class_name == class_name,
                AuthStudent.section == section,
            )

            return [
                student.student_id
                for student in query.all()
            ]

        assigned_classes = _normalize_list(teacher.classes)
        assigned_sections = _normalize_list(teacher.sections)

        if not assigned_classes or not assigned_sections:
            raise AuthorizationError(
                "No class/section assignments are configured for your account."
            )

        students = query.all()

        return [
            student.student_id
            for student in students
            if teacher_handles_class_section(
                teacher,
                student.class_name,
                student.section,
            )
        ]

    raise AuthorizationError("Unsupported role.")


def scope_students_query(
    db: Session,
    caller: dict[str, Any],
    query,
):
    """
    Apply authorization filtering to an existing AuthStudent query.

    Returns a SQLAlchemy query restricted to the caller's permitted student
    records.

    This is preferable to:
        query.all()
        then filtering in Python

    because unauthorized rows never leave the database query boundary.
    """
    role = _caller_role(caller)

    if role == "principal":
        return query

    if role == "student":
        student_id = _caller_id(caller)
        return query.filter(AuthStudent.student_id == student_id)

    if role == "parent":
        parent_id = _caller_id(caller)

        parent = (
            db.query(AuthParent)
            .filter(AuthParent.parent_id == parent_id)
            .first()
        )

        if parent is None:
            raise AuthorizationError("Parent account not found.")

        return query.filter(
            AuthStudent.student_id == parent.child_student_id
        )

    if role == "teacher":
        teacher = get_authenticated_teacher(db, caller)

        students = (
            db.query(AuthStudent)
            .filter(
                AuthStudent.class_name.in_(
                    _normalize_list(teacher.classes)
                ),
                AuthStudent.section.in_(
                    _normalize_list(teacher.sections)
                ),
            )
            .subquery()
        )

        return query.filter(
            AuthStudent.student_id.in_(
                db.query(students.c.student_id)
            )
        )

    raise AuthorizationError("Unsupported role.")


