def require_role(
    caller: dict[str, Any],
    *allowed_roles: str,
) -> None:
    """
    Require the authenticated caller to have one of the supplied roles.

    Example:
        require_role(caller, "teacher")
        require_role(caller, "teacher", "principal")

    The caller's role is read exclusively from auth.py's verified JWT
    context.
    """
    actual_role = _caller_role(caller)

    normalized_allowed = {
        str(role).strip().lower()
        for role in allowed_roles
        if role is not None
    }

    if not normalized_allowed:
        raise AuthorizationError("Authorization policy is not configured.")

    if not normalized_allowed.issubset(ALLOWED_ROLES):
        raise AuthorizationError("Authorization policy contains an invalid role.")

    if actual_role not in normalized_allowed:
        role_list = ", ".join(sorted(normalized_allowed))
        raise AuthorizationError(
            f"This action is only available to {role_list} accounts."
        )


def require_student(caller: dict[str, Any]) -> None:
    require_role(caller, "student")


def require_teacher(caller: dict[str, Any]) -> None:
    require_role(caller, "teacher")


def require_parent(caller: dict[str, Any]) -> None:
    require_role(caller, "parent")


def require_principal(caller: dict[str, Any]) -> None:
    require_role(caller, "principal")


