"""
Centralized authorization / RBAC layer.

Phase 2 only.

Security model
--------------
Authentication is performed exclusively by auth.py.  This module never
accepts a role, user ID, class, section, subject, or student identity from
chat text as proof of authorization.

The trusted caller context must originate from auth.get_current_user():

    {
        "id": "...",
        "role": "teacher|student|parent|principal",
        "name": "..."
    }

The signed JWT is therefore the source of truth for identity.

Authorization rules
-------------------
teacher:
    - Can access only students whose class + section are explicitly assigned
      to the authenticated teacher.
    - Can perform teacher workflows only for assigned class/section.
    - Subject-sensitive operations are additionally restricted to subjects
      listed in auth_teacher.subject_handled.
    - Cannot impersonate another teacher by supplying another teacher_id.

student:
    - Can access only the authenticated student's own records.
    - Cannot request another student's attendance, marks, bio, etc.

parent:
    - Can access only the authenticated parent's child_student_id.
    - child_student_id supplied by the caller is treated only as a requested
      resource and must match the authenticated parent's DB relationship.

principal:
    - School-wide access.
    - No class, section, subject, teacher, or student restriction.

Important:
    This module deliberately fails closed.  Missing/invalid caller fields,
    unknown roles, missing DB records, or malformed authorization data result
    in AuthorizationError rather than an accidental authorization grant.
"""

from __future__ import annotations

from collections.abc import Iterable
from typing import Any

from sqlalchemy.orm import Session

