def verify_attendance_access(
    db: Session,
    caller: dict[str, Any],
    *,
    student_id: str | None = None,
    class_name: str | None = None,
    section: str | None = None,
    write: bool = False,
) -> None:
    """
    Authorization policy for attendance.

    Student:
        own attendance only; read-only.

    Parent:
        linked child's attendance only; read-only.

    Teacher:
        assigned class/section only.
        Read and write are permitted for assigned students.

    Principal:
        school-wide attendance access.
        This helper permits read access but deliberately does not grant
        attendance modification to principals.

    `write=True` is therefore valid only for teachers.
    """
    role = _caller_role(caller)

    if role == "student":
        if write:
            raise AuthorizationError(
                "Students cannot modify attendance."
            )

        verify_student_access(db, caller, student_id)
        return

    if role == "parent":
        if write:
            raise AuthorizationError(
                "Parents cannot modify attendance."
            )

        verify_parent_access(db, caller, student_id)
        return

    if role == "principal":
        if write:
            raise AuthorizationError(
                "Principals cannot modify attendance through this operation."
            )
        return

    if role == "teacher":
        if student_id is not None:
            verify_teacher_student_access(
                db,
                caller,
                student_id,
            )
            return

        if class_name is None or section is None:
            raise AuthorizationError(
                "Class and section are required for teacher attendance access."
            )

        verify_teacher_access(
            db,
            caller,
            class_name=class_name,
            section=section,
        )
        return

    raise AuthorizationError("Your role cannot access attendance data.")


