# ============================================================================

def resolve_teacher_student(
    db: Session,
    caller: dict[str, Any],
    student_id: str,
) -> AuthStudent:
    """
    Explicit replacement for old-style arbitrary student resolution.

    Never call:
        db.query(AuthStudent).get(student_id)

    from a tool without first invoking this guard.
    """
    role = _caller_role(caller)

    if role == "student":
        return verify_student_access(db, caller, student_id)

    if role == "parent":
        return verify_parent_access(db, caller, student_id)

    if role == "teacher":
        return verify_teacher_student_access(db, caller, student_id)

    if role == "principal":
        student = (
            db.query(AuthStudent)
            .filter(AuthStudent.student_id == str(student_id).strip())
            .first()
        )

        if student is None:
            raise AuthorizationError("Student record not found.")

        return student

    raise AuthorizationError("Unsupported role.")


