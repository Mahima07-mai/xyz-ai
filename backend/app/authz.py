# Student authorization
# ============================================================================

def verify_student_access(
    db: Session,
    caller: dict[str, Any],
    student_id: str | None = None,
) -> AuthStudent:
    """
    Verify that a student may access a student record.

    Rules:
        student -> own student_id only
        principal -> any student
        teacher/parent -> denied by this helper

    For a student caller, a missing student_id automatically resolves to
    their authenticated ID.

    If a student explicitly requests another ID, access is denied.
    """
    role = _caller_role(caller)

    if role == "student":
        own_student = get_authenticated_student(db, caller)

        if student_id is not None:
            requested = str(student_id).strip()

            if requested != own_student.student_id:
                raise AuthorizationError(
                    "Students may only access their own student records."
                )

        return own_student

    if role == "principal":
        if student_id is None or not str(student_id).strip():
            raise AuthorizationError("A student ID is required for this lookup.")

        student = (
            db.query(AuthStudent)
            .filter(AuthStudent.student_id == str(student_id).strip())
            .first()
        )

        if student is None:
            raise AuthorizationError("Student record not found.")

        return student

    raise AuthorizationError(
        "This student-access operation is not permitted for your role."
    )


def resolve_own_student(
    db: Session,
    caller: dict[str, Any],
) -> AuthStudent:
    """
    Backwards-compatible helper used by existing tool handlers.

    A student can only resolve their own student account.
    """
    return verify_student_access(db, caller)


# ============================================================================
# Parent -> child authorization
# ============================================================================

def verify_parent_access(
    db: Session,
    caller: dict[str, Any],
    student_id: str | None = None,
) -> AuthStudent:
    """
    Verify that the authenticated parent may access a child.

    The authoritative relationship is AuthParent.child_student_id.

    A parent-supplied student_id is NEVER trusted by itself.  It must equal
    the child_student_id stored on the authenticated parent record.
    """
    parent = get_authenticated_parent(db, caller)

    linked_child_id = str(parent.child_student_id).strip()

    if not linked_child_id:
        raise AuthorizationError(
            "No child is linked to your parent account."
        )

    if student_id is not None:
        requested_id = str(student_id).strip()

        if requested_id != linked_child_id:
            raise AuthorizationError(
                "You are not authorized to access that student's records."
            )

    child = (
        db.query(AuthStudent)
        .filter(AuthStudent.student_id == linked_child_id)
        .first()
    )

    if child is None:
        raise AuthorizationError(
            "The child linked to your account could not be found."
        )

    return child


def resolve_linked_child(
    db: Session,
    caller: dict[str, Any],
    child_name: str | None = None,
) -> AuthStudent:
    """
    Backwards-compatible parent child resolver.

    The new schema permits one child per AuthParent record.  If a parent
    provides a name, the name must match the already-authorized child.
    The name is never used to discover an arbitrary school student.
    """
    child = verify_parent_access(db, caller)

    if child_name:
        requested_name = _normalize(child_name)

        valid_names = {
            _normalize(child.name),
        }

        bio = (
            db.query(StudentBio)
            .filter(StudentBio.student_id == child.student_id)
            .first()
        )

        if bio is not None and bio.student_name:
            valid_names.add(_normalize(bio.student_name))

        if requested_name not in valid_names:
            raise AuthorizationError(
                f"'{child_name}' is not the child linked to your account."
            )

    return child


# ============================================================================
# Teacher class / section scoping
# ============================================================================

def teacher_handles_class_section(
    teacher: AuthTeacher,
    class_name: str,
    section: str,
) -> bool:
    """
    Return whether a teacher is explicitly assigned to the requested
    class + section.

    IMPORTANT:
        AuthTeacher stores classes and sections independently, so the
        schema expresses an allowed class set and an allowed section set.
        Authorization therefore requires membership in BOTH sets.

    This is intentionally strict rather than assuming every class/section
    combination is valid when one dimension matches.
    """
    requested_class = _normalize(class_name)
    requested_section = _normalize(section)

    if not requested_class or not requested_section:
        return False

    assigned_classes = {
        _normalize(value)
        for value in _normalize_list(teacher.classes)
    }

    assigned_sections = {
        _normalize(value)
        for value in _normalize_list(teacher.sections)
    }

    return (
        requested_class in assigned_classes
        and requested_section in assigned_sections
    )


def verify_teacher_access(
    db: Session,
    caller: dict[str, Any],
    *,
    class_name: str | None = None,
    section: str | None = None,
    student_id: str | None = None,
    subject: str | None = None,
) -> AuthTeacher:
    """
    Verify teacher authorization against the teacher's DB-scoped
    assignments.

    Supported checks:
        - teacher role
        - assigned class
        - assigned section
        - assigned student
        - assigned subject

    If student_id is supplied, the student is loaded and its class/section
    must belong to the authenticated teacher.

    Principal is intentionally not accepted here.  Principal operations
    should use require_principal() or their own explicit principal-scoped
    helper so policies cannot accidentally become ambiguous.
    """
    teacher = get_authenticated_teacher(db, caller)

    if class_name is None and section is None and student_id is None and subject is None:
        return teacher

    resolved_class = class_name
    resolved_section = section

    student: AuthStudent | None = None

    if student_id is not None:
        requested_student_id = str(student_id).strip()

        if not requested_student_id:
            raise AuthorizationError("Student ID cannot be empty.")

        student = (
            db.query(AuthStudent)
            .filter(AuthStudent.student_id == requested_student_id)
            .first()
        )

        if student is None:
            raise AuthorizationError("Student record not found.")

        resolved_class = student.class_name
        resolved_section = student.section

    if resolved_class is None or resolved_section is None:
        raise AuthorizationError(
            "Both class and section are required to verify teacher access."
        )

    if not teacher_handles_class_section(
        teacher,
        str(resolved_class),
        str(resolved_section),
    ):
        raise AuthorizationError(
            "You are not authorized to access data for this class and section."
        )

    if student is not None:
        if (
            _normalize(student.class_name) != _normalize(str(resolved_class))
            or _normalize(student.section) != _normalize(str(resolved_section))
        ):
            raise AuthorizationError(
                "The requested student does not belong to the authorized class and section."
            )

    if subject is not None:
        requested_subject = str(subject).strip()

        if requested_subject not in ALLOWED_SUBJECTS:
            raise AuthorizationError("Invalid subject.")

        assigned_subjects = {
            _normalize(value)
            for value in _normalize_list(teacher.subject_handled)
        }

        if _normalize(requested_subject) not in assigned_subjects:
            raise AuthorizationError(
                f"You are not authorized to access {requested_subject} subject data."
            )

    return teacher


def resolve_own_class(
    db: Session,
    caller: dict[str, Any],
) -> tuple[str, str]:
    """
    Resolve a teacher's authorized class/section.

    The new auth_teacher schema stores classes and sections as multi-valued
    JSON arrays.  Therefore this function returns a pair only when there is
    exactly one class and one section.

    For multi-class/multi-section teachers, callers must explicitly specify
    class_name + section and run verify_teacher_access().
    """
    teacher = get_authenticated_teacher(db, caller)

    classes = _normalize_list(teacher.classes)
    sections = _normalize_list(teacher.sections)

    if len(classes) != 1 or len(sections) != 1:
        raise ClarificationNeeded(
            "Your account is assigned to multiple classes or sections. "
            "Please specify the class and section.",
            options=[
                f"{class_name}{section}"
                for class_name in classes
                for section in sections
            ],
        )

    return classes[0], sections[0]


# ============================================================================
# Teacher -> student resolution
# ============================================================================

def resolve_student_in_class(
    db: Session,
    caller: dict[str, Any],
    student_name: str,
    *,
    class_name: str | None = None,
    section: str | None = None,
) -> AuthStudent:
    """
    Resolve exactly one student by name, but ONLY inside a class/section
    already authorized for the authenticated teacher.

    This function never searches the entire school for a teacher.
    """
    teacher = get_authenticated_teacher(db, caller)

    if class_name is None or section is None:
        raise AuthorizationError(
            "Class and section are required for teacher student lookup."
        )

    if not teacher_handles_class_section(teacher, class_name, section):
        raise AuthorizationError(
            "You are not authorized to access that class and section."
        )

    needle = _normalize(student_name)

    if not needle:
        raise AuthorizationError("Student name cannot be empty.")

    students = (
        db.query(AuthStudent)
        .filter(
            AuthStudent.class_name == class_name,
            AuthStudent.section == section,
        )
        .all()
    )

    matches = [
        student
        for student in students
        if needle in _normalize(student.name)
    ]

    if not matches:
        raise AuthorizationError(
            f"No student named '{student_name}' was found in "
            f"{class_name} Section {section}."
        )

    if len(matches) > 1:
        raise ClarificationNeeded(
            f"More than one student matches '{student_name}'. "
            "Please specify the student ID.",
            options=[
                f"{student.name} ({student.student_id})"
                for student in matches
            ],
        )

    return matches[0]


def verify_teacher_student_access(
    db: Session,
    caller: dict[str, Any],
    student_id: str,
    *,
    subject: str | None = None,
) -> AuthStudent:
    """
    Strict teacher -> student authorization.

    The teacher is allowed to access the student only if:
        1. caller role == teacher
        2. teacher exists
        3. student exists
        4. student's class is assigned to teacher
        5. student's section is assigned to teacher
        6. requested subject, if any, is handled by teacher
    """
    student = (
        db.query(AuthStudent)
        .filter(AuthStudent.student_id == str(student_id).strip())
        .first()
    )

    if student is None:
        raise AuthorizationError("Student record not found.")

    verify_teacher_access(
        db,
        caller,
        class_name=student.class_name,
        section=student.section,
        student_id=student.student_id,
        subject=subject,
    )

    return student


