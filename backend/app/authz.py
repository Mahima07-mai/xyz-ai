def get_authenticated_teacher(
    db: Session,
    caller: dict[str, Any],
) -> AuthTeacher:
    """
    Resolve the teacher account using ONLY the authenticated JWT subject.

    No teacher_id supplied by chat/request parameters is ever used to
    establish identity.
    """
    require_teacher(caller)

    teacher_id = _caller_id(caller)

    teacher = (
        db.query(AuthTeacher)
        .filter(AuthTeacher.teacher_id == teacher_id)
        .first()
    )

    if teacher is None:
        raise AuthorizationError(
            "Your teacher account could not be found. Please contact the school office."
        )

    return teacher


def get_authenticated_student(
    db: Session,
    caller: dict[str, Any],
) -> AuthStudent:
    """
    Resolve the authenticated student's own account.
    """
    require_student(caller)

    student_id = _caller_id(caller)

    student = (
        db.query(AuthStudent)
        .filter(AuthStudent.student_id == student_id)
        .first()
    )

    if student is None:
        raise AuthorizationError(
            "Your student account could not be found. Please contact the school office."
        )

    return student


def get_authenticated_parent(
    db: Session,
    caller: dict[str, Any],
) -> AuthParent:
    """
    Resolve the authenticated parent account.

    Parent identity comes from the server-generated parent_id contained
    in the JWT, never from a child_student_id or parent ID supplied by
    the request.
    """
    require_parent(caller)

    parent_id = _caller_id(caller)

    parent = (
        db.query(AuthParent)
        .filter(AuthParent.parent_id == parent_id)
        .first()
    )

    if parent is None:
        raise AuthorizationError(
            "Your parent account could not be found. Please contact the school office."
        )

    return parent


def get_authenticated_principal(
    db: Session,
    caller: dict[str, Any],
) -> AuthPrincipal:
    """
    Resolve the authenticated principal account.

    Kept explicit even though principals generally do not need resource
    resolution, because it provides a DB-backed identity check for
    sensitive principal-only operations.
    """
    require_principal(caller)

    principal_id = _caller_id(caller)

    principal = (
        db.query(AuthPrincipal)
        .filter(AuthPrincipal.principal_id == principal_id)
        .first()
    )

    if principal is None:
        raise AuthorizationError(
            "Your principal account could not be found. Please contact the school office."
        )

    return principal


