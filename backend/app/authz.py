def verify_student_bio_access(
    db: Session,
    caller: dict[str, Any],
    student_id: str,
) -> AuthStudent:
    """
    Verify access to student_bio through the corresponding authenticated
    student record.

    Teacher:
        only students in assigned class/section.

    Student:
        own bio.

    Parent:
        linked child's bio.

    Principal:
        any student's bio.
    """
    role = _caller_role(caller)

    if role == "student":
        return verify_student_access(db, caller, student_id)

    if role == "parent":
        return verify_parent_access(db, caller, student_id)

    if role == "teacher":
        return verify_teacher_student_access(db, caller, student_id)

    if role == "principal":
        student = (
            db.query(AuthStudent)
            .filter(AuthStudent.student_id == str(student_id).strip())
            .first()
        )

        if student is None:
            raise AuthorizationError("Student record not found.")

        return student

    raise AuthorizationError(
        "Your role cannot access student profile information."
    )


def verify_teacher_bio_access(
    db: Session,
    caller: dict[str, Any],
    teacher_id: str | None = None,
) -> AuthTeacher:
    """
    Verify access to teacher_bio.

    Teacher:
        own profile only.

    Principal:
        any teacher profile.

    Student/Parent:
        cannot use this unrestricted teacher-bio lookup.
    """
    role = _caller_role(caller)

    if role == "teacher":
        own_teacher = get_authenticated_teacher(db, caller)

        if teacher_id is not None and str(teacher_id).strip() != own_teacher.teacher_id:
            raise AuthorizationError(
                "Teachers may only access their own teacher profile."
            )

        return own_teacher

    if role == "principal":
        if teacher_id is None or not str(teacher_id).strip():
            raise AuthorizationError("Teacher ID is required.")

        teacher = (
            db.query(AuthTeacher)
            .filter(AuthTeacher.teacher_id == str(teacher_id).strip())
            .first()
        )

        if teacher is None:
            raise AuthorizationError("Teacher record not found.")

        return teacher

    raise AuthorizationError(
        "Your role cannot access teacher profile information."
    )


