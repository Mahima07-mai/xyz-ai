def verify_report_scope(
    db: Session,
    caller: dict[str, Any],
    *,
    class_name: str | None = None,
    section: str | None = None,
    subject: str | None = None,
) -> list[str]:
    """
    Authorize an analytics/report scope and return the exact student IDs
    that may participate in the report.

    This prevents an LLM-generated report query such as:

        "all failing Science students"

    from bypassing the caller's data boundary.

    Teacher:
        class + section must be explicitly assigned.
        subject, if specified, must be taught by the teacher.

    Student:
        only their own student record.

    Parent:
        only their linked child.

    Principal:
        unrestricted school-wide report scope.
    """
    role = _caller_role(caller)

    if role == "teacher":
        if class_name is None or section is None:
            raise AuthorizationError(
                "Teachers must specify an authorized class and section "
                "for analytical reports."
            )

        verify_teacher_access(
            db,
            caller,
            class_name=class_name,
            section=section,
            subject=subject,
        )

        return authorized_student_ids(
            db,
            caller,
            class_name=class_name,
            section=section,
        )

    if role == "student":
        if class_name is not None or section is not None:
            student = get_authenticated_student(db, caller)

            if class_name is not None and _normalize(student.class_name) != _normalize(class_name):
                raise AuthorizationError(
                    "Students cannot request reports for another class."
                )

            if section is not None and _normalize(student.section) != _normalize(section):
                raise AuthorizationError(
                    "Students cannot request reports for another section."
                )

        if subject is not None and subject not in ALLOWED_SUBJECTS:
            raise AuthorizationError("Invalid subject.")

        return authorized_student_ids(db, caller)

    if role == "parent":
        child = verify_parent_access(db, caller)

        if class_name is not None and _normalize(child.class_name) != _normalize(class_name):
            raise AuthorizationError(
                "The requested report is outside your child's scope."
            )

        if section is not None and _normalize(child.section) != _normalize(section):
            raise AuthorizationError(
                "The requested report is outside your child's scope."
            )

        if subject is not None and subject not in ALLOWED_SUBJECTS:
            raise AuthorizationError("Invalid subject.")

        return [child.student_id]

    if role == "principal":
        if subject is not None and subject not in ALLOWED_SUBJECTS:
            raise AuthorizationError("Invalid subject.")

        return authorized_student_ids(
            db,
            caller,
            class_name=class_name,
            section=section,
        )

    raise AuthorizationError("Unsupported role.")


